const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const files = ['ml-content', 'ai-courses', 'dsa-system-design', 'os-networking', 'programming-languages'];
const catalog = {};
for (const file of files) {
    const source = fs.readFileSync(path.join(root, 'js', file + '.js'), 'utf8');
    const data = vm.runInNewContext('const courseData = {};\n' + source + '\ncourseData', {}, { timeout: 5000 });
    for (const [collection, modules] of Object.entries(data)) {
        catalog[collection] = modules.map((module, index) => ({
            number: module.number,
            title: module.title,
            description: module.description,
            duration: module.duration,
            lessons: module.detailedContent.length + ' lessons',
            isNew: module.isNew,
            isLocked: module.isLocked,
            hasCode: module.detailedContent.some(section => Boolean(section.code)),
            lazyContent: { file: file + '.js', collection, index }
        }));
    }
}
const output = '// Generated by npm run content:catalog. Edit the source course bundles, not this file.\nObject.assign(courseData, ' + JSON.stringify(catalog, null, 2) + ');\n';
const target = path.join(root, 'js', 'course-catalog.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
        console.error('Course catalog is stale. Run npm run content:catalog.');
        process.exitCode = 1;
    }
} else {
    fs.writeFileSync(target, output);
    console.log('Generated catalog for ' + Object.values(catalog).flat().length + ' published course modules.');
}
